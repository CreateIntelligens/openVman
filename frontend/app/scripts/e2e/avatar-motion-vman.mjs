// Runs before application scripts. Every intercepted browser operation still
// calls its real native implementation; audio is tapped in parallel with the
// real speaker destination, never substituted or generated by this harness.
function instrumentBrowser(captureFlash = false) {
  const probe = window.__vmanMotionE2e = {
    documentId: `${Date.now()}-${Math.random()}`, factoryCalls: 0, wasmCalls: 0,
    frames: 0, lastFrameAt: 0, events: [], taps: [], sources: new Set(),
    window: { name: 'bootstrap', states: [], peak: 0, samples: 0, sumSquares: 0, speakingPeak: 0, firstSoundState: null },
    flashFrames: [],
    pageEvents: [],
  };
  if (captureFlash) {
    const pageEvent = (type, details = {}) => {
      probe.pageEvents.push({ type, documentId: probe.documentId, phase: probe.window.name, at: performance.now(), wallTime: Date.now(),
        fullscreen: document.fullscreenElement?.tagName ?? null, visibility: document.visibilityState,
        overlays: [...document.querySelectorAll('.error-overlay,.start-overlay,.avatar-overlay.loading,dialog[open],.session-state')].map(node => node.className),
        appConnected: Boolean(document.querySelector('.app-shell')), ...details });
    };
    for (const name of ['fullscreenchange', 'visibilitychange', 'webglcontextlost', 'webglcontextrestored']) {
      document.addEventListener(name, event => pageEvent(name, { target: event.target?.id }), true);
    }
    for (const name of ['pageshow', 'pagehide', 'beforeunload']) window.addEventListener(name, () => pageEvent(name));
    window.addEventListener('keydown', event => { if (event.key === 'Escape') pageEvent('escape'); }, true);
    let pageIdentity = '';
    const inspectPage = () => {
      const signature = JSON.stringify({ app: Boolean(document.querySelector('.app-shell')),
        overlays: [...document.querySelectorAll('.error-overlay,.start-overlay,.avatar-overlay.loading,dialog[open],.session-state')].map(node => node.className) });
      if (signature !== pageIdentity) { pageIdentity = signature; pageEvent('page-layer-change'); }
    };
    new MutationObserver(inspectPage).observe(document, { childList: true, subtree: true, attributes: true, attributeFilter: ['open', 'class'] });
  }
  let factory;
  Object.defineProperty(window, 'createQtAppInstance', {
    configurable: true,
    get: () => factory,
    set(value) {
      factory = typeof value === 'function' ? function (...args) {
        probe.factoryCalls += 1;
        return Reflect.apply(value, this, args);
      } : value;
    },
  });
  for (const name of ['instantiate', 'instantiateStreaming']) {
    const original = WebAssembly[name];
    if (original) WebAssembly[name] = function (...args) {
      probe.wasmCalls += 1;
      return Reflect.apply(original, this, args);
    };
  }
  const drawImage = CanvasRenderingContext2D.prototype.drawImage;
  CanvasRenderingContext2D.prototype.drawImage = function (source, ...args) {
    const result = Reflect.apply(drawImage, this, [source, ...args]);
    if (this.canvas.id === 'canvas_video' && source instanceof HTMLVideoElement) {
      probe.frames += 1;
      probe.lastFrameAt = performance.now();
    }
    return result;
  };
  const NativeContext = window.AudioContext ?? window.webkitAudioContext;
  if (!NativeContext || !window.MediaRecorder) throw new Error('瀏覽器缺少真實 AudioContext 或 MediaRecorder');
  const mixer = new NativeContext();
  const recordingDestination = mixer.createMediaStreamDestination();
  const taps = new WeakMap();
  const tappedNodes = new WeakSet();
  const connect = AudioNode.prototype.connect;
  AudioNode.prototype.connect = function (...args) {
    const result = Reflect.apply(connect, this, args);
    if (args[0] === this.context.destination && !tappedNodes.has(this)) {
      tappedNodes.add(this);
      let tap = taps.get(this.context);
      if (!tap) {
        const analyser = this.context.createAnalyser();
        analyser.fftSize = 1024;
        const destination = this.context.createMediaStreamDestination();
        Reflect.apply(connect, analyser, [destination]);
        const input = mixer.createMediaStreamSource(destination.stream);
        Reflect.apply(connect, input, [recordingDestination]);
        tap = { analyser, data: new Float32Array(analyser.fftSize), input };
        taps.set(this.context, tap);
        probe.taps.push(tap);
      }
      Reflect.apply(connect, this, [tap.analyser, args[1] ?? 0, 0]);
    }
    return result;
  };
  const startSource = AudioBufferSourceNode.prototype.start;
  AudioBufferSourceNode.prototype.start = function (...args) {
    const result = Reflect.apply(startSource, this, args);
    probe.sources.add(this);
    this.addEventListener('ended', () => probe.sources.delete(this), { once: true });
    return result;
  };
  const chunks = [];
  const mimeType = MediaRecorder.isTypeSupported('audio/webm;codecs=opus') ? 'audio/webm;codecs=opus' : 'audio/webm';
  const recorder = new MediaRecorder(recordingDestination.stream, { mimeType });
  recorder.addEventListener('dataavailable', (event) => { if (event.data.size) chunks.push(event.data); });
  probe.audioStartedAt = Date.now();
  recorder.start(500);
  void mixer.resume();
  probe.finishAudio = async () => {
    if (recorder.state !== 'inactive') await new Promise((done) => {
      recorder.addEventListener('stop', done, { once: true });
      recorder.stop();
    });
    const blob = new Blob(chunks, { type: recorder.mimeType });
    const bytes = new Uint8Array(await blob.arrayBuffer());
    let binary = '';
    for (let i = 0; i < bytes.length; i += 16384) binary += String.fromCharCode(...bytes.subarray(i, i + 16384));
    return { base64: btoa(binary), size: blob.size, type: blob.type, startedAt: probe.audioStartedAt };
  };
  const state = () => document.querySelector('.avatar-canvas')?.getAttribute('data-motion-state')?.toLowerCase() ?? '';
  let last = '';
  const sampleCanvas = document.createElement('canvas');
  sampleCanvas.width = 36; sampleCanvas.height = 64;
  const sampleContext = sampleCanvas.getContext('2d', { willReadFrequently: true });
  const stats = () => {
    const pixels = sampleContext.getImageData(0, 0, 36, 64).data;
    let alpha = 0, luma = 0, wall = 0, wallN = 0;
    for (let i = 0; i < pixels.length; i += 4) {
      alpha += pixels[i + 3]; luma += (pixels[i] + pixels[i + 1] + pixels[i + 2]) / 3;
      if (i / 4 < 36 * 8) { wall += (pixels[i] + pixels[i + 1] + pixels[i + 2]) / 3; wallN++; }
    }
    return { alpha: alpha / 2304 / 255, luma: luma / 2304, wall: wall / wallN };
  };
  const tick = () => {
    const value = state();
    const element = document.querySelector('.avatar-canvas');
    const identity = `${element?.getAttribute('data-char-id')}|${value}|${element?.getAttribute('data-motion-enabled')}`;
    if (identity !== last) {
      probe.events.push({ at: performance.now(), state: value, charId: element?.getAttribute('data-char-id'), frames: probe.frames });
      last = identity;
    }
    if (value && !probe.window.states.includes(value)) probe.window.states.push(value);
    if (captureFlash && value && element?.getAttribute('data-char-id') === 'hciot-motion') {
      const canvas = document.getElementById('canvas_video'), held = document.getElementById('avatar-motion-held');
      if (canvas?.width && canvas.height && probe.flashFrames.length < 12000) {
        sampleContext.clearRect(0, 0, 36, 64); sampleContext.drawImage(canvas, 0, 0, 36, 64);
        const raw = stats(), opacity = Number(held?.style.opacity ?? 0);
        if (held?.width && opacity > 0) { sampleContext.globalAlpha = opacity; sampleContext.drawImage(held, 0, 0, 36, 64); sampleContext.globalAlpha = 1; }
        probe.flashFrames.push({ at: performance.now(), wallTime: Date.now(), state: value,
          transition: element.getAttribute('data-motion-transitioning'), opacity, raw, visible: stats(),
          mediaTime: window.characterVideo?.currentTime, width: canvas.width, height: canvas.height });
      }
    }
    requestAnimationFrame(tick);
  };
  requestAnimationFrame(tick);
  setInterval(() => {
    let maximum = 0;
    for (const tap of probe.taps) {
      tap.analyser.getFloatTimeDomainData(tap.data);
      for (const sample of tap.data) {
        maximum = Math.max(maximum, Math.abs(sample));
        probe.window.sumSquares += sample * sample;
        probe.window.samples += 1;
      }
    }
    probe.window.peak = Math.max(probe.window.peak, maximum);
    if (state() === 'speaking') probe.window.speakingPeak = Math.max(probe.window.speakingPeak, maximum);
    if (maximum > 0.003 && probe.window.firstSoundState === null) probe.window.firstSoundState = state();
    probe.latestPeak = maximum;
  }, 20);
}

async function observed(label) {
  const value = await page.evaluate(() => {
    const probe = window.__vmanMotionE2e;
    const stage = document.querySelector('.avatar-canvas');
    const video = window.characterVideo;
    return {
      documentId: probe.documentId, factoryCalls: probe.factoryCalls, wasmCalls: probe.wasmCalls,
      frames: probe.frames, lastFrameAge: performance.now() - probe.lastFrameAt,
      state: stage?.getAttribute('data-motion-state')?.toLowerCase(),
      transitioning: stage?.getAttribute('data-motion-transitioning') === 'true',
      pending: Number(stage?.getAttribute('data-motion-pending') ?? 0),
      enabled: stage?.getAttribute('data-motion-enabled'), profile: stage?.getAttribute('data-motion-profile'),
      charId: stage?.getAttribute('data-char-id'),
      mediaTime: video?.currentTime, mediaDuration: video?.duration, mediaSource: video?.currentSrc || video?.src,
      audioSources: probe.sources.size, latestPeak: probe.latestPeak ?? 0,
      window: { ...probe.window }, events: [...probe.events],
    };
  });
  current.observations.push({ label, at: new Date().toISOString(), ...value });
  return value;
}

async function mark(name) {
  await page.evaluate((name) => {
    window.__vmanMotionE2e.window = { name, states: [], peak: 0, samples: 0, sumSquares: 0, speakingPeak: 0, firstSoundState: null };
  }, name);
}

async function waitState(state, timeout = chatTimeout) {
  await page.waitForFunction((state) => {
    const stage = document.querySelector('.avatar-canvas');
    return stage?.getAttribute('data-motion-state')?.toLowerCase() === state
      && stage.getAttribute('data-motion-transitioning') !== 'true';
  }, state, { timeout });
}

async function ready(id, motion = true) {
  await page.waitForFunction(({ id, motion }) => {
    const stage = document.querySelector('.avatar-canvas');
    const canvas = document.getElementById('canvas_video');
    const probe = window.__vmanMotionE2e;
    return stage?.getAttribute('data-char-id') === id
      && stage.getAttribute('data-motion-enabled') === String(motion)
      && (!motion || (stage.getAttribute('data-motion-pending') === '0'
        && stage.getAttribute('data-motion-transitioning') !== 'true'))
      && !stage.querySelector('.avatar-overlay.loading') && canvas?.width > 0
      && probe.frames > 3 && performance.now() - probe.lastFrameAt < 1500;
  }, { id, motion }, { timeout: readyTimeout });
  if (motion) {
    const value = await observed(`ready-${id}`);
    assert.match(value.profile ?? '', /hciot/i, '新人物未使用 HCIOT 動作 profile');
    assert.ok(value.mediaDuration >= 31.9, 'pilot 正式舞台沒有載入完整動作時間軸');
  }
}

async function canvasFrame(label) {
  const canvas = page.locator('#canvas_video');
  const pixels = await canvas.evaluate((source) => {
    const sample = document.createElement('canvas'); sample.width = 64; sample.height = 64;
    const context = sample.getContext('2d', { willReadFrequently: true });
    context.drawImage(source, 0, 0, 64, 64);
    const data = context.getImageData(0, 0, 64, 64).data;
    let opaque = 0, lit = 0, sum = 0, squared = 0;
    for (let i = 0; i < data.length; i += 4) {
      const value = (data[i] + data[i + 1] + data[i + 2]) / 3;
      if (data[i + 3] > 16) opaque++;
      if (data[i + 3] > 16 && value > 20) lit++;
      sum += value; squared += value * value;
    }
    return { opaque, lit, variance: squared / 4096 - (sum / 4096) ** 2 };
  });
  assert.ok(pixels.opaque > 40 && pixels.lit > 40 && pixels.variance > 2, `${label}: canvas 透明、全黑或只有背景`);
  const value = await observed(label);
  assert.ok(value.lastFrameAge < 1500, `${label}: canvas 已停止繪圖`);
  current.frames.push({ label, ...pixels, frames: value.frames });
  await page.screenshot({ path: join(artifactDir, `${current.id}-${label}.png`) });
}

const resource = (item) => item.protocol !== 'blob:'
  && (item.path.startsWith('/static/characters/') || /\.wasm(?:[./]|$)/i.test(item.path));
async function stableBaseline() {
  let previous = -1, stableAt = Date.now();
  while (Date.now() - stableAt < 1000) {
    const count = current.requests.filter(resource).length;
    if (count !== previous) { previous = count; stableAt = Date.now(); }
    await sleep(120);
  }
  const value = await observed('resource-baseline');
  assert.ok(value.factoryCalls > 0 && value.wasmCalls > 0, '未觀察到真實 factory/WASM 初始化');
  current.baseline = { documentId: value.documentId, factoryCalls: value.factoryCalls,
    wasmCalls: value.wasmCalls, requests: current.requests.filter(resource), mediaSource: value.mediaSource, frames: value.frames };
}
async function assertNoReload(label) {
  const value = await observed(label);
  const baseline = current.baseline;
  assert.equal(value.documentId, baseline.documentId, `${label}: 文件重新載入`);
  assert.equal(value.factoryCalls, baseline.factoryCalls, `${label}: SDK/runtime factory 重啟`);
  assert.equal(value.wasmCalls, baseline.wasmCalls, `${label}: WASM 重啟`);
  assert.deepEqual(current.requests.filter(resource), baseline.requests, `${label}: ready 後重新載入人物資料或影片`);
  assert.equal(value.mediaSource, baseline.mediaSource, `${label}: 動作/聊天更換來源影片`);
  assert.ok(value.frames > baseline.frames, `${label}: canvas 未持續呈現`);
}

