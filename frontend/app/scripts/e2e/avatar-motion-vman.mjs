async function oneShot(state, name, start, end) {
  await mark(`gesture-${state}`);
  await page.getByRole('button', { name, exact: true }).click();
  await waitState(state, 15000);
  const before = await observed(`${state}-started`);
  const begun = Date.now();
  let maxTime = before.mediaTime, completed = false;
  let previousTime = before.mediaTime;
  while (Date.now() - begun < 15000) {
    const value = await observed(`${state}-progress`);
    if (value.transitioning) { await sleep(60); continue; }
    if (value.state === state) {
      assert.ok(value.mediaTime >= start - 0.3 && value.mediaTime <= end + 0.3, `${name}: 不在原動作時間軸`);
      assert.ok(value.mediaTime >= previousTime - 0.5, `${name}: one-shot 動作發生倒退或循環`);
      previousTime = value.mediaTime;
      maxTime = Math.max(maxTime, value.mediaTime);
    } else if (value.state === 'idle') { completed = true; break; }
    else assert.fail(`${name}: 被未預期狀態 ${value.state} 取代`);
    await sleep(110);
  }
  assert.ok(completed && maxTime >= end - 0.5 && Date.now() - begun > 7000, `${name}: 未完成整段動作便回待機`);
  await canvasFrame(`gesture-${state}-idle`);
  await assertNoReload(`gesture-${state}-no-reload`);
  pass(`${current.id}-${state}-one-shot`, { maxTime, durationMs: Date.now() - begun });
}

