async function realChat(cancel = false) {
  await mark(cancel ? 'chat-cancel' : 'chat-normal');
  const beforeRequests = current.chat.length;
  const beforeTts = current.tts.length;
  if (!cancel) {
    await page.getByRole('button', { name: '比心', exact: true }).click();
    await waitState('greeting', 15000);
    await sleep(500);
  }
  await sendMessage(cancel
    ? '請用三句簡短繁體中文介紹一般接待服務，不要提供醫療建議。'
    : '你好，請只用一句繁體中文打招呼，不要提供醫療建議。');
  await page.waitForFunction(() => window.__vmanMotionE2e.window.states.includes('thinking'), null, { timeout: chatTimeout });
  await page.waitForFunction(() => {
    const value = window.__vmanMotionE2e.window;
    return value.states.includes('speaking') && value.speakingPeak > 0.003;
  }, null, { timeout: chatTimeout });
  await canvasFrame(cancel ? 'cancel-speaking' : 'actual-speaking');
  if (cancel) {
    await page.getByRole('button', { name: '停止回答', exact: true }).click();
    await waitState('idle', 10000);
    await sleep(800);
    await mark('after-cancel');
    for (let i = 0; i < 50; i++) {
      const value = await observed('after-cancel');
      assert.equal(value.state, 'idle', '停止後被過期手勢/聊天切回其他狀態');
      assert.ok(value.latestPeak < 0.02, '停止後仍有舊音訊播放');
      await sleep(240);
    }
  } else {
    await page.waitForFunction(() => {
      const stage = document.querySelector('.avatar-canvas');
      return stage?.getAttribute('data-motion-state') === 'idle'
        && window.__vmanMotionE2e.latestPeak < 0.01 && !document.querySelector('.chat-stop-btn');
    }, null, { timeout: chatTimeout });
    const value = await observed('real-chat-finished');
    assert.ok(value.window.states.includes('thinking') && value.window.states.includes('speaking'), '未觀察到真實思考/說話');
    assert.ok(value.window.speakingPeak > 0.003, 'speaking 期間沒有實際可聽音訊');
    assert.equal(value.window.firstSoundState, 'speaking', '第一段實際語音開始時人物尚未切到 speaking');
    assert.ok((await page.locator('.chat-msg.ai:not(.thinking) .chat-text').last().innerText()).trim(), '真實回答氣泡為空');
  }
  assert.ok(current.chat.length > beforeRequests, '沒有實際聊天 POST');
  assert.ok(current.tts.slice(beforeTts).some((item) => item.status >= 200 && item.status < 300), '這輪沒有成功的真實 TTS 回應');
  await assertNoReload(cancel ? 'cancel-no-reload' : 'chat-no-reload');
  pass(`${current.id}-${cancel ? 'real-stop-cancels-audio-and-stale-motion' : 'real-thinking-speaking-idle-with-audible-tts'}`);
}

async function finalizeProject() {
  if (!context) return;
  const activePage = page;
  const nativeVideo = activePage?.video();
  try {
    if (activePage && !activePage.isClosed()) {
      if (captureFlash) {
        const frames = await activePage.evaluate(() => window.__vmanMotionE2e.flashFrames);
        await writeFile(join(artifactDir, `${current.id}-flash-frames.json`), JSON.stringify(frames));
        current.pageEvents = await activePage.evaluate(() => window.__vmanMotionE2e.pageEvents);
      }
      const audio = await activePage.evaluate(() => window.__vmanMotionE2e?.finishAudio());
      if (audio?.size) {
        current.audioFile = join(artifactDir, `${current.id}-actual-audio.webm`);
        await writeFile(current.audioFile, Buffer.from(audio.base64, 'base64'));
        current.audioStartedAt = audio.startedAt;
      }
    }
  } finally {
    await context.close(); context = undefined; page = undefined;
  }
  if (nativeVideo) current.silentPageVideo = await nativeVideo.path();
  if (captureFlash && compositorFrames.length) {
    const frameDir = join(artifactDir, `${current.id}-compositor`); await mkdir(frameDir, { recursive: true });
    const index = [];
    for (let i = 0; i < compositorFrames.length; i++) {
      const name = `${String(i).padStart(4, '0')}.jpg`, frame = compositorFrames[i];
      await writeFile(join(frameDir, name), Buffer.from(frame.data, 'base64'));
      index.push({ name, metadata: frame.metadata });
    }
    await writeFile(join(frameDir, 'index.json'), JSON.stringify(index));
    compositorFrames = [];
  }
  if (current.audioFile && current.silentPageVideo) {
    const offset = Math.max(0, (current.audioStartedAt - current.pageOpenedAt) / 1000);
    current.uiAudioVideo = join(artifactDir, `${current.id}-ui-audio.mp4`);
    await runFile('ffmpeg', ['-y', '-hide_banner', '-loglevel', 'error',
      '-i', current.silentPageVideo, '-itsoffset', String(offset), '-i', current.audioFile,
      '-map', '0:v:0', '-map', '1:a:0', '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '23',
      '-c:a', 'aac', '-af', 'apad', '-shortest', '-movflags', '+faststart', current.uiAudioVideo,
    ], { timeout: 180000 });
    const { stderr } = await runFile('ffmpeg', ['-hide_banner', '-nostats', '-i', current.uiAudioVideo,
      '-map', '0:a:0', '-af', 'volumedetect', '-vn', '-f', 'null', '-'], { timeout: 45000 });
    const mean = stderr.match(/mean_volume:\s*([-+\d.]+|[-+]?inf)\s*dB/i)?.[1];
    const maximum = stderr.match(/max_volume:\s*([-+\d.]+|[-+]?inf)\s*dB/i)?.[1];
    current.audioVolume = { meanVolumeDb: mean ?? null, maxVolumeDb: maximum ?? null, offsetSeconds: offset };
    assert.ok(mean && maximum && Number.isFinite(Number(mean)) && Number.isFinite(Number(maximum))
      && Number(maximum) > -50, '正式 UI 錄影沒有實際非靜音語音');
    pass(`${current.id}-actual-ui-and-audio-recording`, { file: current.uiAudioVideo, ...current.audioVolume });
  } else if (report.failure) current.recordingIncomplete = '測試在真實語音開始前停止；只保留原始 UI 錄影。';
  else assert.fail('未產生實際 UI 或音訊錄影');
}

