import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(app, '../shared/avatar-engine');
const target = resolve(app, 'public/avatar-engine');
await rm(target, { recursive: true, force: true });
await mkdir(resolve(target, 'core/inference'), { recursive: true });
await mkdir(resolve(target, 'inference'), { recursive: true });
for (const name of ['index.mjs', 'renderer.mjs', 'character-adapter.mjs', 'frame-player.mjs', 'frame-sync.mjs']) {
  await cp(resolve(source, name), resolve(target, 'core', name));
}
await cp(resolve(source, 'inference/streaming-playback.mjs'), resolve(target, 'core/inference/streaming-playback.mjs'));
for (const name of ['streaming-worker.js', 'streaming-fbank.js']) {
  await cp(resolve(source, 'inference', name), resolve(target, 'inference', name));
}
// Geometry, morphs, coverage and dental paint are generated by the v2 engine; the
// encrypted mouth model is the only shipped asset.
await cp(resolve(source, 'assets/models'), resolve(target, 'models'), { recursive: true });
const manifest = {};
async function fingerprint(directory, prefix = '') {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name), name = `${prefix}${entry.name}`;
    if (entry.isDirectory()) await fingerprint(path, `${name}/`);
    else {
      const bytes = await readFile(path);
      manifest[name] = { bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') };
    }
  }
}
await fingerprint(target);
await writeFile(resolve(target, 'manifest.json'), JSON.stringify({ files: manifest }, null, 2));
console.log(`Avatar engine: ${Object.keys(manifest).length} pinned runtime files`);
